def react_codegen_node(state: AgentState):
    log_line(state, "ReAct agent: generating code + requirements via tool actions...")

    system_prompt = f"""
You are a ReAct-style coding agent.

GOAL:
Generate a complete Windows Python application in:
- src/main.py
- requirements.txt

MANDATORY RULES:
1) Use ONLY these tools: write_file, read_file.
2) You MUST write src/main.py and requirements.txt using write_file.
3) requirements.txt must include ONLY required packages.
4) The app MUST run with: python src/main.py
5) The app MUST support: --help (print usage and exit).
6) The application MUST show this exact line somewhere visible to the user:
{COPYRIGHT_LINE}
7) NEVER include null bytes. Output must be plain UTF-8 text.
8) After you finish writing files, STOP calling tools.

User requirement:
{state["requirements"]}
""".strip()

    state["messages"] = [SystemMessage(content=system_prompt)]

    for step in range(1, MAX_REACT_STEPS + 1):
        log_line(state, f"ReAct step {step}: thinking + acting...")

        resp = llm.invoke(state["messages"])
        state["messages"].append(resp)

        tool_calls = getattr(resp, "tool_calls", None)
        if not tool_calls:
            log_line(state, "ReAct: no more tool calls → codegen complete.")
            state["status"] = "Files written."
            return state

        for tc in tool_calls:
            tool_name = tc["name"]
            tool_args = tc["args"]

            log_line(state, f"Tool call: {tool_name}({list(tool_args.keys())})")

            tool_fn = next((t for t in TOOLS_LIST if t.name == tool_name), None)
            if tool_fn is None:
                out = f"ERROR: unknown tool {tool_name}"
            else:
                out = tool_fn.invoke(tool_args)

            state["messages"].append(ToolMessage(tool_call_id=tc["id"], content=str(out)))
            log_line(state, f"Tool result: {str(out)[:120]}")

    log_line(state, "ReAct: max steps reached (continuing).")
    state["status"] = "Files written."
    return state

def sanity_node(state: AgentState):
    log_line(state, "Sanity check: python -m py_compile src/main.py")
    rc, out, err = run_cmd("python -m py_compile src/main.py", cwd=state["run_dir"], timeout=120)

    if rc != 0:
        log_line(state, "Auto-repair in progress... (This is normal and automatic)")
        log_line(state, (err or out)[:1200])
        state["status"] = "Sanity failed."
    else:
        state["status"] = "Sanity passed."
    return state

def patch_node(state: AgentState):
    if state["status"] == "Sanity passed.":
        return state

    if state["patch_round"] >= MAX_PATCH_ROUNDS:
        state["status"] = "FAILED: max patch rounds reached."
        log_line(state, state["status"])
        return state

    state["patch_round"] += 1
    log_line(state, f"Patch round {state['patch_round']}...")

    logs_tail = "\n".join(state["logs"][-140:])

    system_prompt = f"""
You are a ReAct-style debugger.

Sanity check failed. Logs:
{logs_tail}

You MUST:
- Fix src/main.py (and requirements.txt if needed)
- Use write_file only
- Make minimal changes
- Ensure python -m py_compile src/main.py will pass
- Ensure app still meets requirement and includes the copyright {COPYRIGHT_LINE}.

Stop calling tools when done.
""".strip()

    state["messages"] = [SystemMessage(content=system_prompt)]

    for step in range(1, MAX_REACT_STEPS + 1):
        log_line(state, f"Patch ReAct step {step}...")

        resp = llm.invoke(state["messages"])
        state["messages"].append(resp)

        tool_calls = getattr(resp, "tool_calls", None)
        if not tool_calls:
            log_line(state, "Patch ReAct: no more tool calls → patch applied.")
            state["status"] = "Patch applied."
            return state

        for tc in tool_calls:
            tool_name = tc["name"]
            tool_args = tc["args"]

            log_line(state, f"Tool call: {tool_name}({list(tool_args.keys())})")

            tool_fn = next((t for t in TOOLS_LIST if t.name == tool_name), None)
            if tool_fn is None:
                out = f"ERROR: unknown tool {tool_name}"
            else:
                out = tool_fn.invoke(tool_args)

            state["messages"].append(ToolMessage(tool_call_id=tc["id"], content=str(out)))
            log_line(state, f"Tool result: {str(out)[:120]}")

    state["status"] = "Patch applied."
    return state

def github_build_node(state: AgentState):
    run_id = os.path.basename(state["run_dir"])
    log_line(state, f"Pushing code to unique branch: build-{run_id}...")

    branch_name = push_to_unique_branch(state["run_dir"], run_id)

    log_line(state, f"Triggering GitHub Actions Windows build on branch={branch_name}...")
    trigger_workflow(branch_name)

    time.sleep(4)

    run_id_gh = get_latest_run_id(branch_name=branch_name)
    if not run_id_gh:
        raise RuntimeError("No workflow run found after dispatch.")

    log_line(state, f"GitHub Actions run_id={run_id_gh} started. Waiting...")
    conclusion = wait_for_run_completion(run_id_gh, timeout_sec=900)
    log_line(state, f"GitHub Actions completed: {conclusion}")

    if conclusion != "success":
        state["status"] = f"EXE build failed on GitHub: {conclusion}"
        return state

    log_line(state, "Downloading artifact zip...")
    artifact_zip = download_artifact_zip(run_id_gh, state["run_dir"])

    log_line(state, "Extracting app.exe...")
    exe_path = extract_exe(artifact_zip, state["run_dir"])

    state["exe_path"] = exe_path
    state["status"] = "BUILD SUCCESSFUL"
    return state

