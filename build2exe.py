workflow = StateGraph(AgentState)

workflow.add_node("scaffold", scaffold_node)
workflow.add_node("react_codegen", react_codegen_node)
workflow.add_node("sanity", sanity_node)
workflow.add_node("patch", patch_node)
workflow.add_node("github_build", github_build_node)

workflow.add_edge(START, "scaffold")
workflow.add_edge("scaffold", "react_codegen")
workflow.add_edge("react_codegen", "sanity")

def after_sanity(state: AgentState) -> str:
    if state["status"] == "Sanity passed.":
        return "github_build"
    else:
        return "patch"

workflow.add_conditional_edges("sanity", after_sanity, {"github_build": "github_build", "patch": "patch"})
workflow.add_edge("patch", "sanity")
workflow.add_edge("github_build", END)

agent = workflow.compile()

