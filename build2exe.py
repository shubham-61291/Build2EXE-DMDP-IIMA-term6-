def run_agent(requirements: str):
    run_dir = init_run_dir()
    thread_local.current_run_dir = run_dir

    state: AgentState = {
        "requirements": requirements,
        "run_dir": run_dir,
        "status": "Initializing...",
        "logs": [],
        "messages": [],
        "patch_round": 0,
        "exe_path": None
    }

    yield "Initializing...", "", None

    try:
        for event in agent.stream(state):
            for node_name, node_state in event.items():
                state = node_state
                status = state.get("status", "Running...")
                logs = "\n".join(state.get("logs", [])[-600:])
                exe_path = state.get("exe_path")
                if exe_path and not os.path.exists(exe_path):
                    exe_path = None
                file_out = gr.File(value=exe_path) if exe_path else None
                yield f"{status} (node={node_name})", logs, file_out

        final_exe = state.get("exe_path")
        if final_exe and os.path.exists(final_exe):
            yield "BUILD SUCCESSFUL — app.exe is ready for download", "\n".join(state.get("logs", [])[-600:]), gr.File(value=final_exe)

    except Exception as e:
        logs = "\n".join(state.get("logs", [])[-600:])
        yield f"ERROR: {str(e)}", logs, None

