API = "https://api.github.com"

def gh_headers():
    return {
        "Authorization": f"token {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json"
    }

def gh_get(url):
    r = requests.get(url, headers=gh_headers())
    if r.status_code >= 300:
        raise RuntimeError(f"GitHub GET failed: {r.status_code} {r.text[:400]}")
    return r.json()

def push_to_unique_branch(run_dir: str, run_id: str) -> str:
    branch_name = f"build-{run_id}"

    local_repo = os.path.join(run_dir, "repo")
    if os.path.exists(local_repo):
        shutil.rmtree(local_repo)

    repo_url = f"https://{GITHUB_TOKEN}@github.com/{GITHUB_USER}/{GITHUB_REPO}.git"
    rc, out, err = run_cmd(f"git clone {repo_url} {local_repo}", cwd=run_dir, timeout=300)
    if rc != 0:
        raise RuntimeError("git clone failed:\n" + (err or out)[-1000:])

    rc, out, err = run_cmd(f"git checkout -b {branch_name}", cwd=local_repo, timeout=120)
    if rc != 0:
        raise RuntimeError("git checkout -b failed:\n" + (err or out)[-1000:])

    ensure_dir(os.path.join(local_repo, "src"))
    shutil.copy(os.path.join(run_dir, "src", "main.py"), os.path.join(local_repo, "src", "main.py"))
    shutil.copy(os.path.join(run_dir, "requirements.txt"), os.path.join(local_repo, "requirements.txt"))

    run_cmd("git config user.email 'bot@colab.local'", cwd=local_repo)
    run_cmd("git config user.name 'Colab Bot'", cwd=local_repo)

    run_cmd("git add .", cwd=local_repo)
    run_cmd(f"git commit -m \"Auto build {run_id}\"", cwd=local_repo)

    rc, out, err = run_cmd(f"git push origin {branch_name}", cwd=local_repo, timeout=300)
    if rc != 0 and "nothing to commit" not in (out + err).lower():
        raise RuntimeError("git push failed:\n" + (err or out)[-1000:])

    return branch_name

def trigger_workflow(branch_name: str):
    url = f"{API}/repos/{GITHUB_USER}/{GITHUB_REPO}/actions/workflows/{WORKFLOW_FILE}/dispatches"
    payload = {"ref": branch_name}
    r = requests.post(url, headers=gh_headers(), json=payload)
    if r.status_code != 204:
        raise RuntimeError(f"Workflow dispatch failed: {r.status_code} {r.text[:400]}")

def get_latest_run_id(branch_name: str = None):
    url = f"{API}/repos/{GITHUB_USER}/{GITHUB_REPO}/actions/runs?per_page=5"
    if branch_name:
        url += f"&branch={branch_name}"

    data = gh_get(url)
    runs = data.get("workflow_runs", [])
    if not runs:
        return None
    return runs[0]["id"]

def wait_for_run_completion(run_id: int, timeout_sec=900):
    start = time.time()
    while time.time() - start < timeout_sec:
        url = f"{API}/repos/{GITHUB_USER}/{GITHUB_REPO}/actions/runs/{run_id}"
        data = gh_get(url)
        status = data.get("status")
        conclusion = data.get("conclusion")
        if status == "completed":
            return conclusion
        time.sleep(5)
    raise RuntimeError("Timed out waiting for GitHub Actions run to complete.")

def download_artifact_zip(run_id: int, run_dir: str) -> str:
    url = f"{API}/repos/{GITHUB_USER}/{GITHUB_REPO}/actions/runs/{run_id}/artifacts"
    data = gh_get(url)
    artifacts = data.get("artifacts", [])
    if not artifacts:
        raise RuntimeError("No artifacts found in run.")

    target = None
    for a in artifacts:
        if a.get("name") == "windows-exe":
            target = a
            break

    if not target:
        raise RuntimeError(f"Artifact 'windows-exe' not found. Found: {[a.get('name') for a in artifacts]}")

    download_url = target["archive_download_url"]
    r = requests.get(download_url, headers=gh_headers(), stream=True)
    if r.status_code >= 300:
        raise RuntimeError(f"Artifact download failed: {r.status_code} {r.text[:200]}")

    out_zip = os.path.join(run_dir, "release", "windows-exe.zip")
    ensure_dir(os.path.dirname(out_zip))

    with open(out_zip, "wb") as f:
        for chunk in r.iter_content(chunk_size=8192):
            if chunk:
                f.write(chunk)

    return out_zip

def extract_exe(artifact_zip: str, run_dir: str) -> str:
    out_dir = os.path.join(run_dir, "release")
    ensure_dir(out_dir)

    with zipfile.ZipFile(artifact_zip, "r") as z:
        z.extractall(out_dir)

    found = None
    for root, _, files in os.walk(out_dir):
        for fn in files:
            if fn.lower() == "app.exe":
                found = os.path.join(root, fn)
                break
        if found:
            break

    if not found or not os.path.exists(found):
        raise RuntimeError("app.exe not found inside artifact zip.")

    final_exe = os.path.join(run_dir, "release", "app.exe")
    if os.path.abspath(found) == os.path.abspath(final_exe):
        return final_exe

    shutil.copy(found, final_exe)
    return final_exe

